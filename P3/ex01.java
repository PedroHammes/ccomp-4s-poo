// Exercício 1 – Estrutura For – Tabuada de multiplicar por 5
// Escreva um programa em Java para escrever uma tabuada de multiplicar por 5.

public class ex01
{
    public static void main(String[] args)
    {
        
        for (int i = 1; i <=10; i++)
        {
            System.out.printf("%d x 5 = %d\n", i, (i*5));
        }

    }
}
